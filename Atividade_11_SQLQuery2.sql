FROM FILME AS F
JOIN LOCACOES AS L ON F.COD_FILME = L.COD_FILME
JOIN CLIENTES AS C ON L.COD_CLIENTE = C.COD_CLIENTE
WHERE C.NOME = 'Renata Cristina';

-- Exercicio 16
SELECT C.NOME, COUNT(L.COD_FILME) AS TotalFilmesAlugados
FROM CLIENTES AS C
JOIN LOCACOES AS L ON C.COD_CLIENTE = L.COD_CLIENTE
GROUP BY C.NOME
HAVING COUNT(L.COD_FILME) > 3;

